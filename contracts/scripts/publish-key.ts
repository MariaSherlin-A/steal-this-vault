/**
 * Writes the vault owner's secp256k1 private key into core/src/published.ts.
 *
 * That key is public on purpose: the project's claim is that it is not enough.
 * This script never touches the mnemonic's other product, the ML-DSA-87 key.
 *
 * It refuses to run unless the key belongs to the deployed vaults' owner and
 * that owner already has a post-quantum key with proof of possession on record,
 * because publishing the key of an unprotected account would hand it over.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { NativeLane, accountFromMnemonic } from "@stv/core/native";
import { repoRoot, requireSecret } from "@stv/core/node";
import { getAddress } from "viem";
import { privateKeyToAccount } from "viem/accounts";

const root = repoRoot();
const deployment = JSON.parse(readFileSync(join(root, "deployments", "testnet.json"), "utf8")) as {
  owner: { evm: string; native: string };
};

const owner = await accountFromMnemonic(requireSecret("VAULT_MNEMONIC"));
const privateKey = owner.privateKey as `0x${string}`;

if (getAddress(owner.evm) !== getAddress(deployment.owner.evm)) {
  throw new Error("VAULT_MNEMONIC is not the owner of the deployed vaults");
}
if (privateKeyToAccount(privateKey).address !== getAddress(owner.evm)) {
  throw new Error("derived key does not match the owner address");
}
const status = await new NativeLane().pqcStatus(owner.cosmos);
if (!status.registered || !status.possessionProven) {
  throw new Error("the owner has no post-quantum key with proof of possession on record; refusing to publish");
}

const file = `/**
 * The vault owner's secp256k1 private key. PUBLIC ON PURPOSE.
 *
 * On any other EVM chain, this line would be the end of the owner's funds.
 * Here the account also has an ML-DSA-87 key on record, and the chain and the
 * vault both ask for it. That second key is not in this repository.
 *
 * Testnet only. This account has never held, and must never hold, real funds.
 * Generated by contracts/scripts/publish-key.ts.
 */
export const PUBLISHED_KEY = "${privateKey}" as const;

/** The account that key controls on the EVM lane. */
export const OWNER_EVM = "${getAddress(owner.evm)}" as const;

/** The same account on the native lane. */
export const OWNER_NATIVE = "${owner.cosmos}" as const;
`;
writeFileSync(join(root, "core", "src", "published.ts"), file);
console.log(`published the secp256k1 key of ${getAddress(owner.evm)} to core/src/published.ts`);
