/**
 * Compiles contracts/src with solc (the JavaScript build, so it runs anywhere Node runs).
 *
 * Writes:
 *   contracts/artifacts/<Name>.json     abi, bytecode, deployed bytecode
 *   contracts/artifacts/solc-input.json the exact compiler input, for source verification
 *   core/src/abi.ts                     the ABIs the rest of the repo imports
 */
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const solc = require("solc") as {
  version(): string;
  compile(input: string, callbacks?: { import: (path: string) => { contents: string } | { error: string } }): string;
};

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const srcDir = join(root, "src");
const outDir = join(root, "artifacts");
const quiet = process.argv.includes("--quiet");

/** Contracts whose ABI is exported to the rest of the repo. */
const EXPORTED = ["Vault", "HybridAccount"] as const;

function solidityFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return solidityFiles(path);
    return name.endsWith(".sol") ? [path] : [];
  });
}

const sources: Record<string, { content: string }> = {};
for (const file of solidityFiles(srcDir)) {
  sources[relative(root, file).replaceAll("\\", "/")] = { content: readFileSync(file, "utf8") };
}

const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: {
      "*": { "*": ["abi", "evm.bytecode.object", "evm.deployedBytecode.object", "evm.methodIdentifiers"] },
    },
  },
};

/** Resolve `@openzeppelin/...` and other package imports from node_modules. */
function findImport(path: string): { contents: string } | { error: string } {
  try {
    return { contents: readFileSync(require.resolve(path), "utf8") };
  } catch {
    return { error: `not found: ${path}` };
  }
}

interface SolcOutput {
  errors?: { severity: string; formattedMessage: string }[];
  contracts?: Record<
    string,
    Record<
      string,
      {
        abi: unknown[];
        evm: {
          bytecode: { object: string };
          deployedBytecode: { object: string };
          methodIdentifiers: Record<string, string>;
        };
      }
    >
  >;
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImport })) as SolcOutput;

const problems = output.errors ?? [];
const errors = problems.filter((e) => e.severity === "error");
// OpenZeppelin's transient reentrancy guard triggers a general advisory about
// EIP-1153. It clears its slot at the end of each call, which is the safe use.
const warnings = problems.filter(
  (e) => e.severity !== "error" && !e.formattedMessage.includes("@openzeppelin/contracts/utils/TransientSlot.sol"),
);
for (const w of warnings) console.warn(w.formattedMessage);
if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "solc-input.json"), JSON.stringify(input, null, 2));

const abis: Record<string, unknown[]> = {};
const sizes: string[] = [];
for (const [file, contracts] of Object.entries(output.contracts ?? {})) {
  if (!file.startsWith("src/")) continue; // skip library sources pulled in from node_modules
  for (const [name, contract] of Object.entries(contracts)) {
    const bytecode = `0x${contract.evm.bytecode.object}`;
    const deployedBytecode = `0x${contract.evm.deployedBytecode.object}`;
    writeFileSync(
      join(outDir, `${name}.json`),
      JSON.stringify(
        {
          contractName: name,
          sourceName: file,
          compiler: solc.version(),
          abi: contract.abi,
          bytecode,
          deployedBytecode,
          methodIdentifiers: contract.evm.methodIdentifiers,
        },
        null,
        2,
      ),
    );
    abis[name] = contract.abi;
    if (deployedBytecode.length > 2) sizes.push(`${name} ${(deployedBytecode.length - 2) / 2} bytes`);
  }
}

const abiFile = [
  "// Generated by contracts/scripts/compile.ts. Do not edit by hand.",
  `// solc ${solc.version()}`,
  "",
  ...EXPORTED.flatMap((name) => {
    const abi = abis[name];
    if (!abi) throw new Error(`contract ${name} was not compiled`);
    return [`export const ${name[0]!.toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;`, ""];
  }),
].join("\n");
writeFileSync(resolve(root, "../core/src/abi.ts"), abiFile);

if (!quiet) {
  console.log(`solc ${solc.version()}`);
  console.log(`compiled ${sizes.length} contracts: ${sizes.join(", ")}`);
  if (warnings.length > 0) console.log(`${warnings.length} warning(s)`);
}
